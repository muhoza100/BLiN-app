export function getCreatorLevel(points: number): {
  title: string;
  levelNumber: number;
  nextThreshold: number;
  prevThreshold: number;
} {
  if (points >= 5000) {
    return { title: 'BLiN Legend', levelNumber: 4, prevThreshold: 5000, nextThreshold: 10000 };
  }
  if (points >= 1000) {
    return { title: 'Star Creator', levelNumber: 3, prevThreshold: 1000, nextThreshold: 5000 };
  }
  if (points >= 250) {
    return { title: 'Rising Creator', levelNumber: 2, prevThreshold: 250, nextThreshold: 1000 };
  }
  return { title: 'Beginner', levelNumber: 1, prevThreshold: 0, nextThreshold: 250 };
}
